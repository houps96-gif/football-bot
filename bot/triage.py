from bot import config
from bot.llm import LLM
from bot.llm.base import TRIAGE_SCHEMA
from bot.models import NewsItem

SYSTEM = """Ты — выпускающий редактор русскоязычного Telegram-канала о европейском футболе. Канал публикует 10–15 главных новостей в день и ценится за то, что в нём нет мусора.

На вход — события, которые уже отобраны для канала, и список новостей из RSS в формате «id | источник | заголовок | анонс». Языки разные: английский, испанский, итальянский, немецкий, французский, русский.

Для КАЖДОЙ новости верни элемент с тем же id:

relevant — true, если это новость о мужском профессиональном футболе. false — другие виды спорта, женский футбол, ТВ и сериалы, ставки и букмекеры, фэнтези-советы, реклама, онлайн-трансляции «live», подборки и рейтинги.

importance — важность от 1 до 10 для аудитории, которая следит за европейским футболом:
  9–10 — трансфер звезды или рекордный трансфер, увольнение или назначение тренера топ-клуба, итог матча плей-офф Лиги чемпионов, финала или главного дерби, досрочное чемпионство, тяжёлая травма звезды мирового уровня.
  7–8 — результат важного матча топ-лиги или еврокубка, официальный трансфер заметного игрока, травма ключевого игрока топ-клуба, крупная дисквалификация или санкции, заявление с реальными последствиями.
  5–6 — рядовые травмы и возвращения, пресс-конференции без новостей, результаты матчей середняков, трансферы игроков среднего уровня.
  3–4 — слухи из вторых рук, мнения экспертов и бывших игроков, прогнозы, интервью без фактов.
  1–2 — ретро, лайфстайл, «10 фактов», фэнтези, тактические разборы без новости.
  Слух — не выше 6, если только это не трансфер мирового уровня от надёжного источника. Анонс будущего матча без события — не выше 5.

league — к чему относится новость: АПЛ, ЛаЛига, СерияА, Бундеслига, Лига1 — внутренние турниры этих стран (чемпионат, кубки); ЛЧ, ЛЕ, ЛК — Лига чемпионов, Лига Европы, Лига конференций; Сборные — сборные, Евро, чемпионат мира и отборы; Другое — всё остальное (другие лиги, МЛС, Саудовская Аравия, ФИФА и УЕФА вне турниров).

event — суть события по-английски, 5–8 слов, только факты, фамилии латиницей без диакритики, без оценок и прилагательных. Пример: «Mbappe hamstring injury out three weeks». Одно и то же событие из разных источников и на разных языках должно получить максимально похожее описание — по нему ищутся дубли.

duplicate — true, если новость сообщает о том же событии, что и одно из событий в блоке «Уже в канале», или о том же, что другая новость выше в этом списке. Одно событие — это один факт: тот же трансфер, та же травма, тот же матч, то же увольнение, даже если источники пишут о нём разными словами и на разных языках. Новое развитие событий (трансфер был слухом — стал официальным; игрок травмирован — объявлен срок) — не дубль.

Верни ровно по одному элементу на каждый id из запроса."""


def triage(llm: LLM, items: list[NewsItem], recent_events: list[str]) -> dict[str, dict]:
    parts = []
    if recent_events:
        parts.append("Уже в канале (за последние 48 часов):\n" + "\n".join(f"- {e}" for e in recent_events[-80:]))
    parts.append("Новости:\n" + "\n".join(f"{it.id} | {it.source} | {it.title} | {it.summary[:200]}" for it in items))
    result = llm.generate_json(SYSTEM, "\n\n".join(parts), TRIAGE_SCHEMA, max_tokens=8192)

    known = {it.id for it in items}
    out = {}
    for row in result.get("items", []):
        if row.get("id") not in known:
            continue
        try:
            importance = int(row.get("importance", 0))
        except (TypeError, ValueError):
            continue
        out[row["id"]] = {
            "relevant": bool(row.get("relevant")),
            "importance": max(1, min(10, importance)),
            "league": row.get("league") if row.get("league") in config.LEAGUES else "Другое",
            "event": str(row.get("event", "")).strip(),
            "duplicate": bool(row.get("duplicate")),
        }
    return out
